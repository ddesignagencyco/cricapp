'use client';

import { useEffect, useState } from 'react';
import toast from 'react-hot-toast';
import { FileEdit, PenLine, Trash2, X } from 'lucide-react';
import {
  AdminAvatar,
  AdminField,
  AdminIconButton,
  AdminInput,
  AdminPageHeader,
  ConfirmDialog,
  EmptyState,
  ErrorState,
  LoadingState,
} from '../../../../components/admin/AdminShared';
import MediaPicker from '../../../../components/admin/MediaPicker';
import {
  createAdminAuthor,
  deleteAdminAuthor,
  fetchAdminAuthors,
  updateAdminAuthor,
  type AdminAuthor,
} from '../../../../services/admin';

const emptyForm = { name: '', bio: '', avatarUrl: '' };

export default function AuthorsPage() {
  const [authors, setAuthors] = useState<AdminAuthor[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(false);
  const [form, setForm] = useState(emptyForm);
  const [editing, setEditing] = useState<AdminAuthor | null>(null);
  const [saving, setSaving] = useState(false);
  const [galleryOpen, setGalleryOpen] = useState(false);
  const [deleteTarget, setDeleteTarget] = useState<AdminAuthor | null>(null);

  const load = () => {
    setLoading(true);
    setError(false);
    fetchAdminAuthors()
      .then(setAuthors)
      .catch(() => setError(true))
      .finally(() => setLoading(false));
  };

  useEffect(() => {
    load();
  }, []);

  const setField = (key: keyof typeof emptyForm, value: string) => {
    setForm((prev) => ({ ...prev, [key]: value }));
  };

  const startEdit = (author: AdminAuthor) => {
    setEditing(author);
    setForm({
      name: author.name,
      bio: author.bio || '',
      avatarUrl: author.avatarUrl || '',
    });
  };

  const cancelEdit = () => {
    setEditing(null);
    setForm(emptyForm);
  };

  const submit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!form.name.trim()) {
      toast.error('Name is required.');
      return;
    }
    setSaving(true);
    const payload = {
      name: form.name.trim(),
      bio: form.bio.trim() || undefined,
      avatarUrl: form.avatarUrl.trim() || undefined,
    };
    try {
      if (editing) {
        const updated = await updateAdminAuthor(editing.id, payload);
        setAuthors((list) => list.map((item) => (item.id === editing.id ? updated : item)).sort((a, b) => a.name.localeCompare(b.name)));
        toast.success('Author updated.');
        cancelEdit();
      } else {
        const created = await createAdminAuthor(payload);
        setAuthors((list) => [...list, created].sort((a, b) => a.name.localeCompare(b.name)));
        setForm(emptyForm);
        toast.success('Author created.');
      }
    } catch {
      toast.error(editing ? 'Could not update the author.' : 'Could not create the author.');
    } finally {
      setSaving(false);
    }
  };

  return (
    <div className="space-y-5">
      <AdminPageHeader title="Authors" subtitle="Editorial bylines used on news. Slugs are generated by the API." />

      <form
        onSubmit={submit}
        noValidate
        className="flex flex-wrap items-end gap-2 rounded-lg p-3"
        style={{ border: '1px solid var(--admin-border)', background: 'var(--admin-card)' }}
      >
        {editing && (
          <p className="w-full text-xs font-semibold" style={{ color: 'var(--admin-text-secondary)' }}>
            Editing {editing.name}
          </p>
        )}
        <div className="w-44">
          <AdminField label="Name" required>
            <AdminInput value={form.name} onChange={(e) => setField('name', e.target.value)} placeholder="Name" />
          </AdminField>
        </div>
        <div className="w-64">
          <AdminField label="Avatar URL">
            <div className="flex gap-2">
              <AdminInput value={form.avatarUrl} onChange={(e) => setField('avatarUrl', e.target.value)} placeholder="Avatar URL" />
              <button
                type="button"
                onClick={() => setGalleryOpen(true)}
                className="shrink-0 rounded-md px-3 text-xs font-bold"
                style={{ border: '1px solid var(--admin-border)', color: 'var(--admin-accent)' }}
              >
                Gallery
              </button>
            </div>
          </AdminField>
        </div>
        <div className="w-64">
          <AdminField label="Bio">
            <AdminInput value={form.bio} onChange={(e) => setField('bio', e.target.value)} placeholder="Short bio" />
          </AdminField>
        </div>
        <button
          type="submit"
          disabled={saving}
          className="btn-brand inline-flex items-center justify-center gap-2 rounded-md px-3 py-2 text-sm font-bold disabled:opacity-60"
        >
          <PenLine size={15} />
          {editing ? 'Save' : 'Create'}
        </button>
        {editing && (
          <button
            type="button"
            onClick={cancelEdit}
            className="inline-flex items-center justify-center gap-2 rounded-md px-3 py-2 text-sm font-semibold"
            style={{ color: 'var(--admin-text-secondary)', border: '1px solid var(--admin-border)' }}
          >
            <X size={15} />
            Cancel
          </button>
        )}
      </form>

      {loading ? (
        <LoadingState />
      ) : error ? (
        <ErrorState message="Could not load authors." onRetry={load} />
      ) : authors.length === 0 ? (
        <EmptyState icon={<PenLine size={28} />} title="No authors yet" message="Create an editorial author to attach to news." />
      ) : (
        <div className="overflow-hidden rounded-lg" style={{ border: '1px solid var(--admin-border)', background: 'var(--admin-card)' }}>
          <div className="table-scroll">
            <table className="w-full text-left text-sm">
            <thead>
              <tr style={{ background: 'var(--admin-table-header)', borderBottom: '1px solid var(--admin-border)' }}>
                <th className="px-4 py-3 text-xs font-bold uppercase tracking-wider" style={{ color: 'var(--admin-text-secondary)' }}>Author</th>
                <th className="px-4 py-3 text-xs font-bold uppercase tracking-wider" style={{ color: 'var(--admin-text-secondary)' }}>Slug</th>
                <th className="px-4 py-3 text-xs font-bold uppercase tracking-wider" style={{ color: 'var(--admin-text-secondary)' }}>Bio</th>
                <th className="px-4 py-3 text-right text-xs font-bold uppercase tracking-wider" style={{ color: 'var(--admin-text-secondary)' }}>Actions</th>
              </tr>
            </thead>
            <tbody>
              {authors.map((author) => (
                <tr
                  key={author.id}
                  style={{
                    borderBottom: '1px solid var(--admin-border)',
                    background: editing?.id === author.id ? 'var(--admin-table-row-hover)' : 'transparent',
                  }}
                  onMouseEnter={(e) => { e.currentTarget.style.background = 'var(--admin-table-row-hover)'; }}
                  onMouseLeave={(e) => { e.currentTarget.style.background = editing?.id === author.id ? 'var(--admin-table-row-hover)' : 'transparent'; }}
                >
                  <td className="px-4 py-3">
                    <div className="flex items-center gap-3">
                      <AdminAvatar name={author.name} src={author.avatarUrl} size={36} />
                      <p className="font-semibold" style={{ color: 'var(--admin-text)' }}>{author.name}</p>
                    </div>
                  </td>
                  <td className="px-4 py-3 font-mono text-xs" style={{ color: 'var(--admin-text-muted)' }}>{author.slug}</td>
                  <td className="max-w-xs px-4 py-3 text-sm" style={{ color: 'var(--admin-text-secondary)' }}>
                    {author.bio || '—'}
                  </td>
                  <td className="px-4 py-3">
                    <div className="flex items-center justify-end gap-1.5">
                      <AdminIconButton label="Edit author" tone="accent" onClick={() => startEdit(author)}>
                        <FileEdit size={16} />
                      </AdminIconButton>
                      <AdminIconButton label="Delete author" tone="danger" onClick={() => setDeleteTarget(author)}>
                        <Trash2 size={16} />
                      </AdminIconButton>
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
          </div>
        </div>
      )}

      <ConfirmDialog
        open={Boolean(deleteTarget)}
        title="Delete author?"
        message={`Remove ${deleteTarget?.name || 'this author'} from the newsroom. Articles keep their byline text.`}
        confirmLabel="Delete"
        danger
        onCancel={() => setDeleteTarget(null)}
        onConfirm={() => {
          if (!deleteTarget) return;
          void deleteAdminAuthor(deleteTarget.id)
            .then(() => {
              setAuthors((list) => list.filter((item) => item.id !== deleteTarget.id));
              if (editing?.id === deleteTarget.id) {
                setEditing(null);
                setForm(emptyForm);
              }
              toast.success('Author deleted.');
            })
            .catch(() => toast.error('Could not delete the author.'))
            .finally(() => setDeleteTarget(null));
        }}
      />

      <MediaPicker
        open={galleryOpen}
        title="Choose author avatar"
        onClose={() => setGalleryOpen(false)}
        onSelect={(url) => {
          setField('avatarUrl', url);
          setGalleryOpen(false);
        }}
      />
    </div>
  );
}
